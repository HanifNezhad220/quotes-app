// Generate realistic intraday price data
function genIntraday(open, volatility, trend, points = 80) {
  const data = [];
  let price = open;
  for (let i = 0; i < points; i++) {
    const hour = 9 + Math.floor((i / points) * 6.5);
    const min = Math.floor(((i / points) * 6.5 * 60) % 60);
    const label = `${hour}:${min.toString().padStart(2, "0")}`;
    price += (Math.random() - 0.5 + trend) * volatility;
    data.push({ time: label, price: parseFloat(price.toFixed(2)) });
  }
  return data;
}

function genSparkline(open, end, points = 20) {
  const data = [];
  for (let i = 0; i < points; i++) {
    const t = i / (points - 1);
    const noise = (Math.random() - 0.5) * (open * 0.015);
    data.push(open + (end - open) * t + noise);
  }
  return data;
}

